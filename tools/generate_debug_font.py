def outputs():
    data=bytearray(1024)
    for char, pattern in GLYPHS.items():
        rows=pattern.split();assert len(rows)==7
        for y,row in enumerate(rows):
            assert len(row)==5
            data[ord(char)*8+y]=int(row,2)<<2
    hexdump=''.join(f'{v:02x}\n' for v in data)
    mif='WIDTH=8;\nDEPTH=1024;\nADDRESS_RADIX=HEX;\nDATA_RADIX=HEX;\nCONTENT BEGIN\n'
    mif+=''.join(f'{i:03X} : {v:02X};\n' for i,v in enumerate(data))+'END;\n'
    return {'rtl/ngage_debug_font.hex':hexdump,'rtl/ngage_debug_font.mif':mif}
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    for name,text in outputs().items():
        path=ROOT/name
        if a.check:
            if path.read_text()!=text:raise SystemExit(f'stale font: {name}')
        else:path.write_text(text)
    print('PASS diagnostic font files match generator' if a.check else 'Generated diagnostic font HEX/MIF')
if __name__=='__main__':main()
