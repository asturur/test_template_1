#!/usr/bin/env python3
"""Configure the pinned stock ARM925T netlist for the NEM-4 phone board."""

import argparse
import hashlib
from pathlib import Path
import re
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / 'rtl/arm9v2'
STOCK_SHA = '087714b2a692fb949bf8a0586674742118383eb18452f1357c4b4e786a69ab4c'


def edit(source, old, new):
    if source.count(old) != 1:
        raise ValueError(f'Expected one occurrence of {old!r}')
    return source.replace(old, new)


def ports(source, last, declarations):
    names = ',\n\t'.join(declaration.split()[-1] for declaration in declarations)
    return edit(source, f'\t{last}\n);',
                f'\t{last},\n\t{names}\n);\n\t' + ';\n\t'.join(declarations) + ';')


def expose(source):
    header, *modules = re.split(r'(?=^module )', source, flags=re.M)
    top, core, system = (next(i for i, part in enumerate(modules)
                              if part.startswith(f'module {name} ('))
                         for name in ('arm925t', 'arm9v2_core', 'zap_top'))
    modules[top] = ports(modules[top], 'dbg_d_rdata', [
        'output wire bus_code', 'output wire bus_lock', 'output wire [2:0] bus_cti',
        'output wire dbg_fetch_valid', 'output wire [31:0] dbg_instruction',
    ])
    modules[top] = edit(modules[top], '\t\t.o_wb_cti(wb_cti),', '''
        .o_wb_cti(wb_cti),
        .o_wb_code(bus_code),
        .o_wb_lock(bus_lock),
        .o_dbg_instruction(dbg_instruction),
        .o_dbg_fetch_valid(dbg_fetch_valid),'''.lstrip('\n'))
    modules[top] = edit(modules[top], '\tassign bus_req',
                        '\tassign bus_cti = wb_cti;\n\tassign bus_req')
    # Match the phone's 16 KiB per cache and 32-byte transport. Keep two ways
    # and publish the actual geometry in the TI cache-type register.
    modules[top] = edit(modules[top], 'CACHE_LINE = 16;', 'CACHE_LINE = 32;')
    modules[top] = edit(modules[top], 'DCACHE_SIZE = 8192;', 'DCACHE_SIZE = 16384;')
    modules[top] = edit(modules[top], '.CP15_CTYPE(32\'h05109149)', '.CP15_CTYPE(32\'h0514a14a)')
    dcache = next(i for i, part in enumerate(modules) if part.startswith('module zap_dcache ('))
    modules[dcache] = edit(modules[dcache], '.INDEX_SIZE(((WAYS == 2) && (CACHE_SIZE > 8192) ? 32\'d8192 : CACHE_SIZE))',
                           '.INDEX_SIZE(CACHE_SIZE)')
    modules[system] = ports(modules[system], 'i_wb_no_late_error', [
        'output wire o_wb_code', 'output wire o_wb_lock',
        'output wire o_dbg_fetch_valid', 'output wire [31:0] o_dbg_instruction',
    ])
    modules[system] = edit(modules[system], '\twire dbg_data_owner;', '''
    wire dbg_data_owner;
    assign o_wb_code = !dbg_data_owner;
    assign o_dbg_instruction = ic_data;
    assign o_dbg_fetch_valid = !s_reset && cpu_instr_stb && instr_ack && !icache_err2;'''.lstrip('\n'))
    modules[system] = edit(modules[system], '.o_data_wb_swp(cpu_dc_swp),',
                           '.o_data_wb_swp(cpu_dc_swp),\n\t\t\t\t.o_swp_lock(o_wb_lock),')
    modules[core] = edit(modules[core], '\to_data_wb_swp,', '\to_data_wb_swp,\n\to_swp_lock,')
    modules[core] = edit(modules[core], '\toutput wire o_data_wb_swp;',
                         '\toutput wire o_data_wb_swp;\n\toutput wire o_swp_lock;')
    modules[core] = edit(modules[core], '\tassign o_data_wb_swp = w_swp;', '''
    assign o_data_wb_swp = w_swp;
    // W owns both phases of SWP, including the clocks between bus beats.
    assign o_swp_lock = !i_reset && w[541] && w_swp;'''.lstrip('\n'))
    # Keep the mainline CPU available to reference simulations. Rename module
    # declarations and instance types only, leaving hierarchy and logic intact.
    names = [re.match(r'module (\w+)', part)[1] for part in modules]
    types = re.compile(r'^(\s*(?:module )?)(' + '|'.join(names) +
                       r')(?= #?\(| \w+\()', flags=re.M)
    return ('// NEM-4 interface generated by tools/gen_arm9v2_phone.py.\n' + header +
            types.sub(r'\1ngage2_\2', ''.join(modules)))


def fold_section_index(phone):
    """Fold the D-side section index while retaining the original tag bits."""
    parts = re.split(r'(?=^module )', phone, flags=re.M)
    data_cache = next(i for i, part in enumerate(parts) if part.startswith('module ngage2_zap_dcache ('))
    tlb = next(i for i, part in enumerate(parts) if part.startswith('module ngage2_zap_tlb ('))
    parts[data_cache] = edit(parts[data_cache], '\t\t.CHECK_WALK(1\'b1),',
                             '\t\t.CHECK_WALK(1\'b1),\n\t\t.SECTION_INDEX_XOR(1\'b1),')
    section_memory = '\tngage2_zap_mem_inv_block #(\n\t\t.WIDTH(44 - $clog2(SECTION_TLB_ENTRIES)),'
    parts[tlb] = edit(parts[tlb], section_memory, '''
    localparam integer SECTION_INDEX_WIDTH = $clog2(SECTION_TLB_ENTRIES);

    // The stored section tag is unchanged. Given that tag, the low page
    // bits can be recovered from the index by applying the same XOR again.
    function [SECTION_INDEX_WIDTH-1:0] section_index;
        input [11:0] section_page;
        reg [11:0] shifted_page;
        begin
            shifted_page = section_page >> SECTION_INDEX_WIDTH;
            section_index = section_page[SECTION_INDEX_WIDTH-1:0];
            if (SECTION_INDEX_XOR)
                section_index = section_index ^ shifted_page[SECTION_INDEX_WIDTH-1:0];
        end
    endfunction
''' + section_memory)
    parts[tlb] = edit(parts[tlb], "\tparameter [0:0] CHECK_WALK = 1'b0;",
                      "\tparameter [0:0] CHECK_WALK = 1'b0;\n\tparameter SECTION_INDEX_XOR = 1'b0;")
    for port, address in (('raddr', 'i_address_nxt'), ('waddr', 'tlb_address')):
        parts[tlb] = edit(parts[tlb], f'.i_{port}({address}[(20 + $clog2(SECTION_TLB_ENTRIES)) - 1:20])',
                          f'.i_{port}(section_index({address}[31:20]))')
    return ''.join(parts)


def expose_block_writeback(phone):
    """Carry each captured 16-byte RAM victim half beside its bus request."""
    parts = re.split(r'(?=^module )', phone, flags=re.M)
    pins = ['input wire i_block_enable', 'output wire o_write_block', 'output wire [127:0] o_block_data']
    index = {name: next(i for i, part in enumerate(parts) if part.startswith(f'module ngage2_{name} ('))
             for name in ('arm925t', 'zap_top', 'zap_dcache', 'zap_dcache_fsm')}
    top = ports(parts[index['arm925t']], 'dbg_instruction', [
        'input tri0 block_enable', 'output wire bus_write_block', 'output wire [127:0] bus_block_data'])
    parts[index['arm925t']] = edit(top, '\t\t.i_clk(clk),', '''		.i_block_enable(block_enable),
		.o_write_block(bus_write_block),
		.o_block_data(bus_block_data),
		.i_clk(clk),''')

    zap = ports(parts[index['zap_top']], 'o_dbg_instruction', pins)
    zap = edit(zap, '\t\t\t) u_data_cache(', '''			) u_data_cache(
				.i_block_enable(i_block_enable),
				.o_write_block(dc_write_block),
				.o_block_data(o_block_data),
				.o_block_address(dc_block_address),''')
    zap = edit(zap, '\twire dc_writeback_busy;', '''	wire dc_writeback_busy, dc_write_block;
	wire [31:0] dc_block_address;''')
    parts[index['zap_top']] = edit(zap, '\t\t\tassign o_wb_we = wb_we;', '''			assign o_wb_we = wb_we;
			assign o_write_block = dbg_data_owner && wb_stb && wb_we && dc_write_block && wb_adr == dc_block_address;''')

    cache_pins = pins + ['output wire [31:0] o_block_address']
    cache = ports(parts[index['zap_dcache']], 'i_wb_err', cache_pins)
    cache = edit(cache, '\t) u_zap_cache_fsm(', '''	) u_zap_cache_fsm(
		.i_block_enable(i_block_enable),
		.o_write_block(victim_write_block),
		.o_block_data(o_block_data),
		.o_block_address(o_block_address),''')
    parts[index['zap_dcache']] = edit(cache, '\twire victim_writeback_busy;', '''	wire victim_writeback_busy, victim_write_block;
	assign o_write_block = state_ff == SELECT_CCH && victim_write_block;''')

    fsm = ports(parts[index['zap_dcache_fsm']], 'i_wb_err', cache_pins)
    fsm = edit(fsm, "\tassign adr_ctr_inc = adr_ctr_ff + {{$clog2(CACHE_LINE / 4) {1'd0}}, 1'd1};", '''
	// Wait for one acknowledgement per half of the captured RAM victim.
	wire block_target = i_block_enable && CACHE_LINE == 32 && wb_adr_cur[31:24] == 8'h0a;
	wire block_beat = block_target && state_ff[CLEAN_SINGLE];
	assign adr_ctr_inc = adr_ctr_ff + (block_beat ? 4'd4 : 4'd1);
	assign o_write_block = block_beat && o_wb_stb_ff && o_wb_adr_ff == wb_adr_cur;
	assign o_block_address = wb_adr_cur;
	assign o_block_data = cache_line[(wb_adr_cur[4] ? 128 : 0)+:128];''')
    if 'wire writeback_next_valid' in fsm:
        fsm = edit(fsm, '\twire writeback_next_valid = (take ? adr_ctr_inc : adr_ctr_ff) <= last_evict_word;', '''	localparam integer EVICT_INDEX_BITS = $clog2(CACHE_LINE / 4) + 1;
	wire [EVICT_INDEX_BITS-1:0] last_block_word = last_evict_word - 4'd3;
	wire [EVICT_INDEX_BITS-1:0] last_writeback_word = block_target ? last_block_word : last_evict_word;
	wire writeback_next_valid = (take ? adr_ctr_inc : adr_ctr_ff) <= last_writeback_word;''')
        fsm = edit(fsm, '(take ? adr_ctr_inc : adr_ctr_ff) == last_evict_word',
                   '(take ? adr_ctr_inc : adr_ctr_ff) == last_writeback_word')
        start = fsm.index('state_ff[UNLOCK_REG]: begin')
        fsm = fsm[:start] + edit(fsm[start:], 'o_wb_cti_nxt = CTI_BURST;',
                                 'o_wb_cti_nxt = block_target && first_evict_word == last_block_word ? CTI_EOB : CTI_BURST;')
    else:
        for counter in ('ff', 'inc'):
            fsm = edit(fsm, f'adr_ctr_{counter}}} != ((CACHE_LINE / 4) - 1)',
                       f'adr_ctr_{counter}}} != ((CACHE_LINE / 4) - (block_beat ? 4 : 1))')
    parts[index['zap_dcache_fsm']] = fsm
    return ''.join(parts)


def schedule_ready_register_shift(phone):
    """Use the forwarded ARM shift count when Rs is already ready."""
    start = phone.index('module ngage2_arm9v2_execute (')
    end = phone.index('\nendmodule', start)
    execute = phone[start:end]
    if 'wire direct_reg_shift =' in execute:
        raise ValueError('The ready register shift is already enabled in this netlist')
    execute = edit(execute, '\tassign o_shift_wait = (i_valid && (i_reg_shift || agu_scaled)) && !prepared;', '''
    wire direct_reg_shift = i_reg_shift && i_kind == DP && !i_thumb && !prepared
                            && i_early[2] && !s_wait[2] && !tag_pc[2] && !tag_psr[2];

    assign o_shift_wait = i_valid && ((i_reg_shift && !direct_reg_shift) || agu_scaled) && !prepared;''')
    # Scaled memory addressing still uses the prepared offset.
    execute = edit(execute, '\t\tplanned_writes_ref = 0;\n\t\tcase (i_kind)', '''
        if (direct_reg_shift) begin
            shift_amount = operand[71:64];
            shift_rot = (shift_type == 0 ? -operand[68:64] : operand[68:64]);
        end
\t\tplanned_writes_ref = 0;
\t\tcase (i_kind)''')
    return phone[:start] + execute + phone[end:]


def schedule_early_smull(phone):
    """Launch ready unconditional ARM SMULL on the S-to-A edge."""
    target = '\t(* multstyle = "dsp" *) reg signed [65:0] full_product;\n'
    start = phone.index(target)
    end = phone.index('\tassign product =', start)
    if 'wire launch_smull =' in phone:
        raise ValueError('Early SMULL is already enabled in this netlist')
    if 'if (product_phase)' not in phone[start:end]:
        raise ValueError('Expected the original multiply product register')
    # Accept waits for forwarded multiplicands. Keep the same product
    # register and use the original clock phase for other multiplies.
    product = '''
    wire launch_smull = accept && i_kind == MULL && i_instruction[22] && !i_instruction[21]
                        && i_condition == 4'he && !i_fault && !i_thumb
                        && i_early[1] && i_early[2] && !s_wait[1] && !s_wait[2];
    wire signed_product = a[327-:4] == MULL && a[474];
    wire signed [32:0] product_left = launch_smull ? {shifted[31], shifted} :
                       {signed_product && a[249], a[249-:32]};
    wire signed [32:0] product_right = launch_smull ? {operand[95], operand[95:64]} :
                        {signed_product && a[185], a[185-:32]};
    (* multstyle = "dsp" *) reg signed [65:0] full_product;
    always @(posedge i_clk)
        if (launch_smull || product_phase)
            full_product <= product_left * product_right;

`ifndef SYNTHESIS
    reg launched_smull;
    wire signed [63:0] check_smull = $signed(right_a) * $signed(special_a);
    always @(posedge i_clk) begin
        if (i_reset || i_flush) launched_smull <= 0;
        else if (accept) launched_smull <= launch_smull;
        else if (finish) launched_smull <= 0;
        if (!i_reset && finish && launched_smull && product !== check_smull) begin
            $display("Incorrect early SMULL operands at %h", a[515-:32]);
            $stop;
        end
    end
`endif
'''
    phone = phone[:start] + product + phone[end:]
    return edit(phone, '\t\t\t\tmultiply_product_ready <= 0;\n\t\t\t\ta[515-:32]',
                '\t\t\t\tmultiply_product_ready <= launch_smull;\n\t\t\t\ta[515-:32]')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--stock', type=Path, help='Use the pinned Quartus-selected donor artifact')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.stock:
        stock = args.stock.read_bytes()
    else:
        build = ROOT / 'build'
        build.mkdir(exist_ok=True)
        with tempfile.TemporaryDirectory(dir=build) as name:
            output = Path(name) / 'arm925t_gen.v'
            subprocess.run(['bash', VENDOR / 'upstream/tools/gen_cpu.sh', output], check=True)
            stock = output.read_bytes()
    if hashlib.sha256(stock).hexdigest() != STOCK_SHA:
        raise ValueError('Donor netlist differs from pinned Quartus input')
    output = VENDOR / 'arm925t_phone.v'
    generated = expose_block_writeback(fold_section_index(expose(stock.decode())))
    generated = schedule_ready_register_shift(generated)
    generated = schedule_early_smull(generated)
    if args.check:
        if output.read_text() != generated:
            raise ValueError('Phone netlist is out of date')
    else:
        output.write_text(generated)


if __name__ == '__main__':
    main()
